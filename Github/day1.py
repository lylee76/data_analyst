# Git => VSC => Version System Control which means it controls different verions of an 
# application or System.
# It tracks our code and the changes made with in the code.

# Github => It is a platform to store our projects
# It has folders to store projects which is known as repositories, or repo

#git flow
# 1. git initialization => git init(done only once for a project)
# U => undefined
# A => added in git
# M => Modified
# 2. add files in git => git add {file_name}
# git add. //add all the files to git at once
# 3. Connect git and github repo
# git remote add origin {SSH_key}
# 4. Commit the changes to github
# git commit -m "Message"
# 5. Push the changes to github
# git push -u origin {branch_name} => always do this for 1st push
# -u => Upstream stores the branch_name so that next push will be in the same branch
# git push => push in the same branch
# git push origin => It is reccommended after the 1st push
